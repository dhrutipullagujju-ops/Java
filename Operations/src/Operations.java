public class Operations {
    public static void main(String[] args){
        int id = 2;
        double quantity = 2.4;
        var a = id + quantity;
        var b = id - quantity;
        var c = id * quantity;
        var d = id / quantity;
        var e = id % quantity;
        System.out.println(a+"\n"+b+"\n"+c+"\n"+d+"\n"+e);


    }
}
